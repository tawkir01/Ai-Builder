"use client";
import { useEffect, useState } from 'react';
import styles from './page.module.css';
import Link from 'next/link';

interface Project {
  title: string;
  description: string;
  techStack: string[];
  status: string;
}

export default function ProjectsPage() {
  const [projects, setProjects] = useState<Project[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    async function loadProjects() {
      const savedPath = localStorage.getItem('aiBuilder_careerPath') || 'Software Engineer';
      const savedLevel = parseInt(localStorage.getItem('aiBuilder_level') || '5', 10);

      try {
        const res = await fetch('/api/ai/projects', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ careerPath: savedPath, level: savedLevel })
        });
        const data = await res.json();
        if (data.projects && Array.isArray(data.projects)) {
          setProjects(data.projects);
        }
      } catch (err) {
        console.error("Failed to load projects:", err);
      } finally {
        setIsLoading(false);
      }
    }
    loadProjects();
  }, []);

  return (
    <div className={styles.container}>
      <main className={styles.mainContent}>
        <div style={{ marginBottom: '2rem', display: 'flex', gap: '1rem', flexWrap: 'wrap' }}>
          <Link href="/dashboard" style={{ color: '#818cf8', textDecoration: 'none' }}>← Dashboard</Link>
          <Link href="/roadmap" style={{ color: '#818cf8', textDecoration: 'none' }}>🗺️ Roadmap</Link>
          <Link href="/opportunities" style={{ color: '#818cf8', textDecoration: 'none' }}>💰 Earning</Link>
          <Link href="/mock-interview" style={{ color: '#818cf8', textDecoration: 'none' }}>🎙️ Interview</Link>
          <Link href="/resume-builder" style={{ color: '#818cf8', textDecoration: 'none' }}>📄 Resume</Link>
        </div>
        <header className={styles.header}>
          <h1>Your Project Portfolio 🛠️</h1>
          <p>Projects generated by AI to match your skill level.</p>
        </header>

        <section className={styles.projectSection}>
          {isLoading ? (
            <div className={`glass ${styles.projectCard}`}>
              <p style={{ textAlign: 'center', padding: '2rem' }}>⏳ Generating personalized project ideas...</p>
            </div>
          ) : projects.length === 0 ? (
            <div className={`glass ${styles.projectCard}`}>
              <p>No projects generated yet.</p>
              <Link href="/diagnosis" style={{ color: '#818cf8' }}>Complete the AI Diagnosis first →</Link>
            </div>
          ) : (
            projects.map((project, idx) => (
              <div key={idx} className={`glass ${styles.projectCard}`}>
                <div className={styles.cardHeader}>
                  <h2>{idx + 1}. {project.title}</h2>
                  <span className={project.status === 'IN PROGRESS' ? styles.status : styles.statusNew}>
                    {project.status}
                  </span>
                </div>
                <p className={styles.description}>{project.description}</p>
                <div className={styles.techStack}>
                  {project.techStack?.map((tech, tIdx) => (
                    <span key={tIdx}>{tech}</span>
                  ))}
                </div>
                <button className={project.status === 'IN PROGRESS' ? styles.btnPrimary : styles.btnSecondary}>
                  {project.status === 'IN PROGRESS' ? 'Continue Building' : 'Start Project'}
                </button>
              </div>
            ))
          )}
        </section>
      </main>
    </div>
  );
}
